from abc import ABC, abstractmethod
from typing import List, Dict, Any


class EmbeddingProvider(ABC):
    """
    Abstract base class for genuine local embedding providers.
    All embeddings generated by subclasses MUST be real dense vectors from actual models.
    Pseudo-vectors, feature hashing, or random vectors are strictly forbidden.
    """

    @abstractmethod
    async def embed_text(self, text: str) -> List[float]:
        """
        Generate a dense embedding vector for a single text chunk or query.
        """
        pass

    @abstractmethod
    async def embed_batch(self, texts: List[str]) -> List[List[float]]:
        """
        Generate dense embedding vectors for a batch of text chunks.
        """
        pass

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Name of the underlying embedding model (e.g. 'nomic-embed-text')."""
        pass

    @property
    @abstractmethod
    def dimension(self) -> int:
        """Dimensionality of the dense vectors (e.g. 768)."""
        pass

    @abstractmethod
    def get_provider_info(self) -> Dict[str, Any]:
        """Returns metadata about the active provider and model."""
        pass
